"""Pinned quantized Horizon model, exact prior sample comparison, no remote code."""
import argparse
import hashlib
import json
from pathlib import Path
from time import perf_counter
from urllib.request import urlopen

from evaluate_semantic import ranged_download
from train_candidates import ROOT, load, metrics

MODEL = 'Horizon-Labs/prompt-injection-guard-small'
REVISION = '2efc2ed5abecd21eb45c2506d231a65d6e392b85'
DEST = ROOT/'models/pretrained/horizon-small'
HASHES = {'model_quantized.onnx':'61cd0741cdbfcc229e32e1de1392f352736d87d1e8b3c2b67ad9836bb7910d5d',
          'tokenizer.json':'47834a7dbbb0c4324fe9569fe47955241594a9ee539c9e478755d6fbc51e5f46'}


def verify(path):
    with path.open('rb') as handle:
        digest = hashlib.file_digest(handle,'sha256').hexdigest()
    if path.name in HASHES and digest != HASHES[path.name]:
        raise ValueError('Upstream checksum mismatch: '+path.name)
    return digest


def download():
    DEST.mkdir(parents=True,exist_ok=True)
    records=[]
    for name in ('README.md','LICENSE','config.json','tokenizer_config.json','tokenizer.json','onnx/model_quantized.onnx'):
        path = DEST/Path(name).name
        url = f'https://huggingface.co/{MODEL}/resolve/{REVISION}/{name}?download=true'
        if not path.exists():
            temp = path.with_suffix(path.suffix+'.partial')
            if path.name in HASHES:
                ranged_download(url,temp)
            else:
                with urlopen(url,timeout=90) as response:
                    temp.write_bytes(response.read())
            if path.name in HASHES:
                with temp.open('rb') as handle:
                    if hashlib.file_digest(handle,'sha256').hexdigest()!=HASHES[path.name]:
                        raise ValueError('Downloaded file checksum mismatch: '+path.name)
            temp.replace(path)
        digest=verify(path)
        records.append(dict(file=path.name,sha256=digest,bytes=path.stat().st_size,url=url))
        # Only generated byte-range parts; source file verified first.
        for part in DEST.glob(path.name+'.partial.*'):
            if part.name.rsplit('.',1)[-1].isdigit():
                part.unlink()
        print(path.name,path.stat().st_size,flush=True)
    (DEST/'manifest.json').write_text(json.dumps(dict(model=MODEL,revision=REVISION,files=records),indent=2),encoding='utf-8')


def evaluate(extended=False):
    import numpy as np
    import onnxruntime as ort
    from tokenizers import Tokenizer
    for filename in HASHES:
        verify(DEST/filename)
    config=json.loads((DEST/'config.json').read_text(encoding='utf-8'))
    positive=next(int(k) for k,v in config['id2label'].items() if v.upper()=='INJECTION')
    options=ort.SessionOptions(); options.intra_op_num_threads=4
    session=ort.InferenceSession(str(DEST/'model_quantized.onnx'),sess_options=options,providers=['CPUExecutionProvider'])
    print('Inputs:',[(i.name,i.type) for i in session.get_inputs()],flush=True)
    tokenizer=Tokenizer.from_file(str(DEST/'tokenizer.json'))
    tokenizer.enable_truncation(max_length=512,stride=64)
    prior=json.loads((ROOT/'docs/semantic_evaluation.json').read_text())
    pools,_=load()
    report=dict(model=MODEL,revision=REVISION,trained_here=False,threshold=.5,window_tokens=512,overlap_tokens=64,
                providers=session.get_providers(),onnxruntime=ort.__version__,extended=extended,evaluations={},
                limitations=['PromptShield is listed as upstream training data; its results are a compatibility check, not independent evidence.',
                             'Previously inspected public suites are regression sets; unknown pretraining overlap remains possible.',
                             '512-token windows match earlier comparison coverage but do not exploit native 8k context.',
                             'Inputs above 20000 characters excluded; single-class suites cannot measure both FPR and recall.'])
    output=ROOT/('docs/horizon_extended_evaluation.json' if extended else 'docs/horizon_evaluation.json')
    for name,predictions in prior['sample_predictions'].items():
        ids={r['text_sha256'] for r in predictions}
        if extended and name!='hendzh__PromptShield_test':
            rows=[r for r in pools[name] if len(r[0])<=20000]
        else:
            rows=[r for r in pools[name] if hashlib.sha256(r[0].encode()).hexdigest() in ids]
            assert len(rows)==len(ids)
        probs,times=[],[]
        for index,(text,label,category) in enumerate(rows):
            start=perf_counter()
            encoded=tokenizer.encode(text)
            values=[]
            for window in [encoded]+encoded.overflowing:
                feed=dict(input_ids=window.ids,attention_mask=window.attention_mask,token_type_ids=window.type_ids)
                logits=session.run(None,{i.name:np.array([feed[i.name]],dtype=np.int64) for i in session.get_inputs()})[0][0]
                exp=np.exp(logits-logits.max())
                values.append(float((exp/exp.sum())[positive]))
            probs.append(max(values)); times.append((perf_counter()-start)*1000)
            if (index+1)%64==0:
                print(name,index+1,'/',len(rows),flush=True)
        result=metrics(rows,np.array(probs),.5)
        result.update(mean_ms=float(np.mean(times)),p95_ms=float(np.percentile(times,95)))
        report['evaluations'][name]=result
        report.setdefault('sample_predictions',{})[name]=[dict(text_sha256=hashlib.sha256(r[0].encode()).hexdigest(),label=r[1],probability=p) for r,p in zip(rows,probs)]
        print(name,json.dumps(result),flush=True)
        output.write_text(json.dumps(report,indent=2),encoding='utf-8')
    report['complete']=True
    report['promoted']=False
    output.write_text(json.dumps(report,indent=2),encoding='utf-8')


if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--download',action='store_true'); parser.add_argument('--extended',action='store_true')
    args=parser.parse_args()
    download() if args.download else evaluate(args.extended)
